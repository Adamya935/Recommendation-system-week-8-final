"""
================================================================================
HYBRID MOVIE RECOMMENDATION SYSTEM — WITH PROPER COLD-START HANDLING
================================================================================
Dataset: Kaggle's "The Movies Dataset"
Files Required in the working directory:
    movies_metadata.csv, credits.csv, keywords.csv,
    ratings_small.csv, links_small.csv

Design summary
---------------
1. Content-based engine: TF-IDF over overview + genres + keywords + cast + director.
2. Collaborative engine: user-user cosine similarity (KNN), fit once and reused.
3. Hybrid engine with three cold-start regimes, each handled explicitly:
     a. No usable movie AND no known user  -> popularity fallback
        (IMDB-style Bayesian weighted rating, not just "first N rows").
     b. Known movie but unknown/new user   -> alpha = 0 (100% content-based).
     c. Known user                         -> alpha rises smoothly with the
        user's rating count (graduated confidence), instead of jumping from
        0 straight to a fixed 0.5 the moment the user has a single rating.
   Item-level cold start is also handled: if a specific candidate movie has
   no collaborative signal (nobody rated it, or it's outside the small-ratings
   sample), that movie's item-level alpha drops to 0 and it is scored purely
   on content — even for an otherwise "warm" user.
4. Content ids and collaborative ids live in different spaces (TMDB id vs.
   MovieLens movieId). links_small.csv is used to bridge collaborative
   output back into TMDB id space *before* merging, so the hybrid blend
   is comparing the same movies rather than two disjoint candidate sets.
================================================================================
"""

import ast
import difflib
import numpy as np
import pandas as pd
from nltk.stem.porter import PorterStemmer
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.metrics.pairwise import cosine_similarity
from sklearn.neighbors import NearestNeighbors


# -----------------------------------------------------------------------------
# 1. DATA PARSING HELPERS
# -----------------------------------------------------------------------------
def genre_extract(col):
    try:
        return [i['name'] for i in ast.literal_eval(col)]
    except Exception:
        return []


def keyword_extract(col):
    try:
        return [i['name'] for i in ast.literal_eval(col)]
    except Exception:
        return []


def cast_extract(col):
    try:
        L = []
        for j, i in enumerate(ast.literal_eval(col)):
            if j >= 3:
                break
            L.append(i['name'])
        return L
    except Exception:
        return []


def crew_extract(col):
    try:
        for i in ast.literal_eval(col):
            if i.get('job') == 'Director':
                return [i['name']]
    except Exception:
        pass
    return []


# -----------------------------------------------------------------------------
# 2. BUILD CONTENT-BASED FEATURE SPACE (keyed by TMDB id, not by title string)
# -----------------------------------------------------------------------------
def build_content_based():
    movies = pd.read_csv('movies_metadata.csv', low_memory=False)
    credits = pd.read_csv('credits.csv')
    keywords = pd.read_csv('keywords.csv')

    movies = movies[movies['id'].apply(lambda x: str(x).isdigit())].copy()
    movies['id'] = movies['id'].astype(int)
    # Dedup by unique id, NOT by title — remakes/reused titles would otherwise collide
    movies = movies.drop_duplicates(subset='id')

    credits['id'] = credits['id'].astype(int)
    keywords['id'] = keywords['id'].astype(int)

    data = movies.merge(credits, on='id').merge(keywords, on='id')
    data = data[['genres', 'id', 'keywords', 'overview', 'title', 'cast', 'crew']]
    data.dropna(subset=['id', 'title'], inplace=True)
    data.reset_index(drop=True, inplace=True)

    data['genres'] = data['genres'].apply(genre_extract)
    data['keywords'] = data['keywords'].apply(keyword_extract)
    data['cast'] = data['cast'].apply(cast_extract)
    data['crew'] = data['crew'].apply(crew_extract)
    data['overview'] = data['overview'].fillna('').apply(lambda x: str(x).split())

    data['cast'] = data['cast'].apply(lambda x: [i.replace(" ", "") for i in x])
    data['crew'] = data['crew'].apply(lambda x: [i.replace(" ", "") for i in x])
    data['genres'] = data['genres'].apply(lambda x: [i.replace(" ", "") for i in x])
    data['keywords'] = data['keywords'].apply(lambda x: [i.replace(" ", "") for i in x])

    data['tags'] = data['overview'] + data['genres'] + data['keywords'] + data['cast'] + data['crew']
    data['clean_tags'] = data['tags'].apply(lambda x: " ".join(x).lower())
    data['title'] = data['title'].apply(lambda x: str(x).lower())

    ps = PorterStemmer()

    def stemming(text):
        return " ".join(ps.stem(word) for word in text.split())

    data['clean_tags'] = data['clean_tags'].apply(stemming)

    tfidf = TfidfVectorizer(max_features=5000, stop_words='english')
    vectors = tfidf.fit_transform(data['clean_tags']).toarray()

    all_titles = data['title'].tolist()
    title_to_pos = {t: i for i, t in enumerate(data['title'])}
    pos_to_id = data['id'].to_dict()
    id_to_title = data.set_index('id')['title'].to_dict()

    return data, vectors, all_titles, title_to_pos, pos_to_id, id_to_title


# -----------------------------------------------------------------------------
# 3. POPULARITY FALLBACK (for true cold start — no user, no seed movie)
# -----------------------------------------------------------------------------
def build_popularity_table():
    """IMDB-style Bayesian weighted rating: WR = (v/(v+m))*R + (m/(v+m))*C"""
    pop = pd.read_csv('movies_metadata.csv', low_memory=False)[['id', 'vote_average', 'vote_count']]
    pop = pop[pop['id'].apply(lambda x: str(x).isdigit())].copy()
    pop['id'] = pop['id'].astype(int)
    pop = pop.drop_duplicates(subset='id')
    pop['vote_average'] = pd.to_numeric(pop['vote_average'], errors='coerce').fillna(0)
    pop['vote_count'] = pd.to_numeric(pop['vote_count'], errors='coerce').fillna(0)

    C = pop['vote_average'].mean()
    m = pop['vote_count'].quantile(0.90)

    pop['weighted_rating'] = (
        pop['vote_count'] / (pop['vote_count'] + m) * pop['vote_average']
        + m / (pop['vote_count'] + m) * C
    )
    return pop.sort_values('weighted_rating', ascending=False).reset_index(drop=True)


# -----------------------------------------------------------------------------
# 4. CONTENT-BASED RECOMMENDER
# -----------------------------------------------------------------------------
def find_closest_titles(query, all_titles, n=5, cutoff=0.5):
    query = query.lower().strip()
    close = difflib.get_close_matches(query, all_titles, n=n, cutoff=cutoff)
    if close:
        return close
    return [t for t in all_titles if query in t][:n]


def recommend_content(movie_title, vectors, all_titles, title_to_pos, pos_to_id, top_n=10):
    """Returns (seed_tmdb_id, [(tmdb_id, similarity), ...]) or (None, []) if not found."""
    q = movie_title.lower().strip()
    if q not in title_to_pos:
        suggestions = find_closest_titles(q, all_titles)
        if suggestions:
            print(f"'{q}' not found in dataset. Did you mean one of these?")
            for s in suggestions:
                print(" -", s)
        else:
            print(f"'{q}' not found in dataset.")
        return None, []

    idx = title_to_pos[q]
    seed_id = pos_to_id[idx]
    sims = cosine_similarity(vectors[idx].reshape(1, -1), vectors).flatten()
    top_idx = sims.argsort()[::-1][1:top_n + 1]
    return seed_id, [(pos_to_id[i], float(sims[i])) for i in top_idx]


