# 8. INTERACTIVE TERMINAL APP
# -----------------------------------------------------------------------------
def run_interactive():
    print("Building content feature space & TF-IDF vectors...")
    data, vectors, all_titles, title_to_pos, pos_to_id, id_to_title = build_content_based()

    print("Building popularity fallback table...")
    popularity_table = build_popularity_table()

    print("Building collaborative matrix & pre-fitting NearestNeighbors model...")
    (user_rating_matrix, movie_columns, user_index, movieid_to_tmdbid,
     nbrs, user_rating_counts, user_means, user_stds) = build_collaborative(data)

    print("\n=======================================================")
    print("HYBRID MOVIE RECOMMENDATION SYSTEM")
    print("Enter a movie title, a user id, both, or neither.")
    print("(type 'quit' to exit)")
    print("=======================================================")

    while True:
        movie = input("\nMovie title (or 'quit'): ").strip()
        if movie.lower() in ('quit', 'exit'):
            break

        raw_id = input("User ID (or press Enter to skip): ").strip()
        user_id = int(raw_id) if raw_id.isdigit() else None

        results = hybrid_recommend(
            movie_title=movie if movie else None,
            user_id=user_id,
            top_n=5,
            vectors=vectors, all_titles=all_titles, title_to_pos=title_to_pos,
            pos_to_id=pos_to_id, id_to_title=id_to_title,
            user_rating_matrix=user_rating_matrix, movie_columns=movie_columns,
            user_index=user_index, movieid_to_tmdbid=movieid_to_tmdbid, nbrs=nbrs,
            user_rating_counts=user_rating_counts, user_means=user_means,
            user_stds=user_stds, popularity_table=popularity_table,
        )

        print("\nRecommendations:")
        if not results:
            print(" (none found)")
        for title, stars in results:
            print(" -", title, f"(Est. \u2605 {stars})")


if __name__ == "__main__":
    run_interactive()
