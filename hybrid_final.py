# 5. COLLABORATIVE FILTERING ENGINE
# -----------------------------------------------------------------------------
def build_collaborative(data):
    ratings = pd.read_csv('ratings_small.csv')
    links = pd.read_csv('links_small.csv')

    links = links.dropna(subset=['tmdbId']).copy()
    links['tmdbId'] = links['tmdbId'].astype(int)

    movie_map = links.merge(data[['id']], left_on='tmdbId', right_on='id', how='inner')
    movie_map = movie_map.drop_duplicates(subset='movieId')
    # Bridge: MovieLens movieId -> TMDB id, so collaborative output can be
    # merged with content output later in a shared id space.
    movieid_to_tmdbid = movie_map.set_index('movieId')['id'].to_dict()

    ratings = ratings.merge(movie_map[['movieId']], on='movieId', how='inner')

    user_pivot = ratings.pivot_table(index='userId', columns='movieId', values='rating').fillna(0)
    user_rating_matrix = user_pivot.values
    movie_columns = user_pivot.columns.to_numpy()
    user_index = {uid: pos for pos, uid in enumerate(user_pivot.index)}

    # Fit once here; reused on every call instead of refitting per-recommendation.
    nbrs = NearestNeighbors(metric='cosine', algorithm='brute')
    if len(user_rating_matrix) > 0:
        nbrs.fit(user_rating_matrix)

    nonzero = user_pivot.where(user_pivot > 0)
    user_rating_counts = nonzero.count(axis=1).to_dict()
    user_means = nonzero.mean(axis=1).to_dict()
    user_stds = nonzero.std(axis=1).fillna(0).to_dict()

    return (user_rating_matrix, movie_columns, user_index, movieid_to_tmdbid,
            nbrs, user_rating_counts, user_means, user_stds)


def recommend_user_based(target_user, user_rating_matrix, movie_columns, user_index,
                          movieid_to_tmdbid, nbrs, user_means=None, top_n=10, k=10,
                          shrinkage_k=2.0):
    """Returns [(tmdb_id, predicted_rating), ...]. Empty list if user is unknown
    or no confident predictions can be made — no exceptions, clean status only.

    A raw prediction backed by only 1-2 neighbors is statistically weak, but
    a similarity-weighted average collapses to exactly that neighbor's rating
    when they're the only one who rated the movie — so a single 5-star vote
    was hitting the ceiling and outranking predictions built from many
    neighbors. Fix: shrink low-support predictions toward the target user's
    own mean rating, in proportion to how many neighbors actually voted
    (support_count). shrinkage_k controls how aggressively: with the default
    of 2.0, a 1-neighbor prediction is pulled about 2/3 of the way back to
    the user's mean, while a 10-neighbor prediction is barely shrunk at all.
    """
    if target_user not in user_index:
        return []

    idx = user_index[target_user]
    n_neighbors = min(k + 1, len(user_rating_matrix))
    distances, indices = nbrs.kneighbors([user_rating_matrix[idx]], n_neighbors=n_neighbors)
    distances, indices = distances.flatten(), indices.flatten()
    sims = 1 - distances

    # Remove the user's own row by matching its actual index, not by
    # assuming it's always in position 0 (safe even with tied/duplicate rows).
    mask = indices != idx
    indices, sims = indices[mask], sims[mask]
    if len(indices) == 0:
        return []

    top_k_ratings = user_rating_matrix[indices]
    weighted_sum = sims @ top_k_ratings
    rated_mask = (top_k_ratings > 0).astype(float)
    weight_totals = sims @ rated_mask
    support_count = rated_mask.sum(axis=0)  # how many neighbors actually rated each movie

    with np.errstate(divide='ignore', invalid='ignore'):
        raw_predicted = np.where(weight_totals > 0, weighted_sum / weight_totals, 0.0)

    user_fallback = user_means.get(target_user, 3.5) if user_means else 3.5
    if user_fallback is None or pd.isna(user_fallback):
        user_fallback = 3.5

    shrinkage = support_count / (support_count + shrinkage_k)
    predicted = np.where(
        weight_totals > 0,
        shrinkage * raw_predicted + (1.0 - shrinkage) * user_fallback,
        0.0,
    )

    target_ratings = user_rating_matrix[idx]
    candidate_mask = (target_ratings == 0) & (weight_totals > 0)
    candidate_positions = np.where(candidate_mask)[0]
    if len(candidate_positions) == 0:
        return []

    order = candidate_positions[np.argsort(predicted[candidate_positions])[::-1]]

    result = []
    for p in order:
        tmdb_id = movieid_to_tmdbid.get(movie_columns[p])
        if tmdb_id is None:
            continue  # no bridge available for this movie — skip rather than mis-key it
        result.append((tmdb_id, float(predicted[p])))
        if len(result) >= top_n:
            break
    return result


# -----------------------------------------------------------------------------
# 6. GRADUATED CONFIDENCE (cold -> warm transition, not a hard 0/0.5 switch)
# -----------------------------------------------------------------------------
def calculate_graduated_alpha(num_ratings, alpha_max=0.85, lambda_decay=0.3):
    """alpha(N) = alpha_max * (1 - e^(-lambda * N)), clipped to [0, alpha_max].
    N=0 -> alpha=0 (pure content). Alpha rises smoothly as ratings accumulate,
    approaching alpha_max but never fully trusting a thin rating history."""
    if num_ratings <= 0:
        return 0.0
    return float(np.clip(alpha_max * (1.0 - np.exp(-lambda_decay * num_ratings)), 0.0, alpha_max))


# -----------------------------------------------------------------------------
# 7. HYBRID ENGINE
# -----------------------------------------------------------------------------
def hybrid_recommend(movie_title, user_id, top_n,
                      vectors, all_titles, title_to_pos, pos_to_id, id_to_title,
                      user_rating_matrix, movie_columns, user_index, movieid_to_tmdbid, nbrs,
                      user_rating_counts, user_means, user_stds, popularity_table):

    seed_id, content_recs = (None, [])
    if movie_title:
        seed_id, content_recs = recommend_content(
            movie_title, vectors, all_titles, title_to_pos, pos_to_id, top_n=top_n * 3
        )

    is_known_user = user_id is not None and user_id in user_index

    # --- Regime A: fully cold (no usable movie AND no known user) ----------
    if seed_id is None and not is_known_user:
        print("[INFO] No usable movie title or known user id — using popularity fallback.")
        top_pop = popularity_table.head(top_n)
        return [
            (id_to_title.get(mid, f"id {mid}"), round(float(wr), 1))
            for mid, wr in zip(top_pop['id'], top_pop['weighted_rating'])
        ]

    # --- Regime B / C: graduated alpha based on how much history exists ----
    num_ratings = user_rating_counts.get(user_id, 0) if is_known_user else 0
    alpha = calculate_graduated_alpha(num_ratings)

    if is_known_user:
        print(f"[INFO] User {user_id}: {num_ratings} ratings on record -> alpha = {alpha:.2f}")
    else:
        print(f"[INFO] User unknown/new -> alpha = 0.00 (pure content, seeded from '{movie_title}')")

    collab_recs = (
        recommend_user_based(user_id, user_rating_matrix, movie_columns, user_index,
                              movieid_to_tmdbid, nbrs, user_means=user_means, top_n=top_n * 3)
        if is_known_user else []
    )

    # --- Pure CF pass-through -----------------------------------------------
    # No movie was given (or the title wasn't found), so the content engine
    # contributed nothing — content_recs is empty. In that case hybrid mode
    # should just BE collaborative filtering: surface CF's own predicted
    # rating directly instead of re-deriving a fresh calibrated star through
    # the alpha-blend formula below (which used to run even with alpha's
    # only input being CF, producing a different-looking number for the
    # exact same ranking). is_known_user is guaranteed True here — the
    # fully-cold case (no movie AND no known user) already returned via
    # Regime A above.
    if not content_recs:
        if not collab_recs:
            print("[INFO] No CF candidates for this user — falling back to popularity.")
            top_pop = popularity_table.head(top_n)
            return [
                (id_to_title.get(mid, f"id {mid}"), round(float(wr), 1))
                for mid, wr in zip(top_pop['id'], top_pop['weighted_rating'])
            ]
        ranked = sorted(collab_recs, key=lambda x: x[1], reverse=True)[:top_n]
        return [
            (id_to_title.get(mid, f"id {mid}"), round(float(max(1.0, min(5.0, rating))), 1))
            for mid, rating in ranked
        ]

    c_dict = dict(content_recs)
    raw_collab = dict(collab_recs)
    # Normalize predicted ratings (roughly 1-5 scale) into a 0-1 relevance score
    collab_dict = {mid: max(0.0, min(1.0, (s - 1.0) / 4.0)) for mid, s in raw_collab.items()}

    all_ids = set(c_dict) | set(collab_dict)
    if not all_ids:
        print("[INFO] No candidates from either engine — falling back to popularity.")
        top_pop = popularity_table.head(top_n)
        return [
            (id_to_title.get(mid, f"id {mid}"), round(float(wr), 1))
            for mid, wr in zip(top_pop['id'], top_pop['weighted_rating'])
        ]

    max_c = max(c_dict.values()) if c_dict else 1.0
    max_cf = max(collab_dict.values()) if collab_dict else 1.0

    u_mean = user_means.get(user_id, 3.5) if is_known_user else 3.5
    u_std = user_stds.get(user_id, 1.0) if is_known_user else 1.0
    if not u_std or pd.isna(u_std):
        u_std = 1.0

    # ONE scoring formula applied to the whole list, chosen once per call
    # (not per item). Using a different formula per item put content- and
    # collaborative-sourced candidates on two incomparable scales, so
    # content items always outranked collaborative ones regardless of
    # alpha. hybrid_score already encodes item-level cold start correctly
    # (item_alpha=0 for items with no collaborative signal), so a single
    # consistent formula is enough — no per-item branching needed.
    use_calibrated_scale = is_known_user and num_ratings > 0

    merged = []
    for mid in all_ids:
        norm_c = (c_dict.get(mid, 0.0) / max_c) if max_c > 0 else 0.0
        norm_cf = (collab_dict.get(mid, 0.0) / max_cf) if max_cf > 0 else 0.0

        # Item-level cold start: if THIS movie has no collaborative signal
        # at all, score it purely on content regardless of the user's alpha.
        has_collab_signal = mid in collab_dict
        item_alpha = alpha if has_collab_signal else 0.0

        hybrid_score = item_alpha * norm_cf + (1.0 - item_alpha) * norm_c

        if use_calibrated_scale:
            stars = u_mean + (hybrid_score - 0.5) * 2.0 * u_std
        else:
            stars = 3.5 + hybrid_score * 1.4

        stars = max(1.0, min(5.0, stars))
        merged.append((id_to_title.get(mid, f"id {mid}"), stars))

    # Sort on the raw float score, not the rounded display value — sorting
    # on rounded stars creates spurious ties (e.g. 3.36 vs 3.39 both -> 3.4)
    # whose break order depends on arbitrary set-iteration order, so the
    # same underlying scores can print in a different order across runs.
    merged.sort(key=lambda x: x[1], reverse=True)
    return [(title, round(stars, 1)) for title, stars in merged[:top_n]]


